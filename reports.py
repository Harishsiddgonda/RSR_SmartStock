from __future__ import annotations

import csv
import io
from typing import Any
import openpyxl
from openpyxl.styles import Alignment, Border, Font, PatternFill, Side
from db import get_db, get_setting


def generate_inventory_valuation_excel() -> io.BytesIO:
    """Generate professional Excel workbook for inventory valuation."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Inventory Valuation"

    currency = get_setting("currency_symbol", "₹")

    # Header styling
    header_fill = PatternFill(start_color="1F2937", end_color="1F2937", fill_type="solid")
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    data_font = Font(name="Calibri", size=10)
    total_font = Font(name="Calibri", size=11, bold=True)
    border_thin = Border(
        left=Side(style="thin", color="E5E7EB"),
        right=Side(style="thin", color="E5E7EB"),
        top=Side(style="thin", color="E5E7EB"),
        bottom=Side(style="thin", color="E5E7EB"),
    )

    # Title rows
    ws.append([f"RSR SmartStock – Inventory Valuation Report"])
    ws.append([f"Currency: {currency} | Generated by RSR SmartStock WMS"])
    ws.append([])
    ws["A1"].font = Font(name="Calibri", size=14, bold=True, color="111827")
    ws["A2"].font = Font(name="Calibri", size=10, italic=True, color="4B5563")

    headers = [
        "Product Name", "SKU", "Barcode", "Category", "Unit",
        "Total Stock", "Reorder Level", "Unit Cost", "Selling Price",
        "Total Cost Value", "Total Retail Value", "Potential Gross Profit", "Status"
    ]
    ws.append(headers)
    header_row = 4

    for col_num, _ in enumerate(headers, 1):
        cell = ws.cell(row=header_row, column=col_num)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center" if col_num > 4 else "left", vertical="center")

    with get_db() as db:
        products = db.execute(
            """SELECT p.*, c.name as category_name, COALESCE(SUM(s.quantity), 0) AS total_stock
               FROM products p
               LEFT JOIN categories c ON c.id = p.category_id
               LEFT JOIN stock s ON s.product_id = p.id
               GROUP BY p.id
               ORDER BY p.name"""
        ).fetchall()

        row_idx = header_row + 1
        total_units = 0
        total_cost_val = 0.0
        total_retail_val = 0.0

        for p in products:
            qty = p["total_stock"]
            cost = p["cost_price"] or 0.0
            retail = p["selling_price"] or 0.0
            c_val = qty * cost
            r_val = qty * retail
            profit = r_val - c_val
            status = "Low Stock" if qty <= p["reorder_level"] else ("Out of Stock" if qty == 0 else "In Stock")

            total_units += qty
            total_cost_val += c_val
            total_retail_val += r_val

            row_data = [
                p["name"],
                p["sku"],
                p["barcode"],
                p["category_name"] or p["category"] or "General",
                p["unit"],
                qty,
                p["reorder_level"],
                cost,
                retail,
                c_val,
                r_val,
                profit,
                status
            ]
            ws.append(row_data)

            for col_idx in range(1, len(headers) + 1):
                cell = ws.cell(row=row_idx, column=col_idx)
                cell.font = data_font
                cell.border = border_thin
                if col_idx in [6, 7]:
                    cell.alignment = Alignment(horizontal="right")
                    cell.number_format = "#,##0"
                elif col_idx in [8, 9, 10, 11, 12]:
                    cell.alignment = Alignment(horizontal="right")
                    cell.number_format = "#,##0.00"

            row_idx += 1

        # Summary total row
        ws.append([
            "TOTAL SUMMARY", "", "", "", "",
            total_units, "", "", "",
            total_cost_val, total_retail_val, total_retail_val - total_cost_val, ""
        ])
        for col_idx in range(1, len(headers) + 1):
            cell = ws.cell(row=row_idx, column=col_idx)
            cell.font = total_font
            cell.fill = PatternFill(start_color="F3F4F6", end_color="F3F4F6", fill_type="solid")
            cell.border = border_thin
            if col_idx in [6, 10, 11, 12]:
                cell.alignment = Alignment(horizontal="right")
                if col_idx == 6:
                    cell.number_format = "#,##0"
                else:
                    cell.number_format = "#,##0.00"

    # Auto-adjust column widths
    for col in ws.columns:
        max_len = 0
        col_letter = col[0].column_letter
        for cell in col:
            val_str = str(cell.value or "")
            if len(val_str) > max_len:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

    output = io.BytesIO()
    wb.save(output)
    output.seek(0)
    return output


def generate_movements_excel(movements: list[dict[str, Any]]) -> io.BytesIO:
    """Generate Excel workbook for stock movements."""
    wb = openpyxl.Workbook()
    ws = wb.active
    ws.title = "Movements Report"

    header_fill = PatternFill(start_color="1F2937", end_color="1F2937", fill_type="solid")
    header_font = Font(name="Calibri", size=11, bold=True, color="FFFFFF")
    data_font = Font(name="Calibri", size=10)
    border_thin = Border(
        left=Side(style="thin", color="E5E7EB"), right=Side(style="thin", color="E5E7EB"),
        top=Side(style="thin", color="E5E7EB"), bottom=Side(style="thin", color="E5E7EB")
    )

    ws.append(["RSR SmartStock – Stock Movements Audit Report"])
    ws.append([])
    ws["A1"].font = Font(name="Calibri", size=14, bold=True)

    headers = [
        "Reference No", "Date & Time", "Type", "Product Name", "SKU",
        "Quantity", "From Warehouse", "To Warehouse", "Party (Supplier/Customer)",
        "Unit Price", "Total Price", "Remarks", "Recorded By"
    ]
    ws.append(headers)
    header_row = 3

    for col_idx, _ in enumerate(headers, 1):
        cell = ws.cell(row=header_row, column=col_idx)
        cell.fill = header_fill
        cell.font = header_font
        cell.alignment = Alignment(horizontal="center" if col_idx in [1, 2, 3] else "left")

    row_idx = header_row + 1
    for m in movements:
        party = m.get("supplier_name") or m.get("customer_name") or "—"
        row_data = [
            m.get("ref_no", ""),
            str(m.get("created_at", ""))[:19],
            m.get("movement_type", ""),
            m.get("product_name", ""),
            m.get("sku", ""),
            m.get("quantity", 0),
            m.get("from_name") or "—",
            m.get("to_name") or "—",
            party,
            m.get("unit_price") or 0.0,
            m.get("total_price") or 0.0,
            m.get("remarks") or "—",
            m.get("user_name") or "System",
        ]
        ws.append(row_data)
        for col_idx in range(1, len(headers) + 1):
            cell = ws.cell(row=row_idx, column=col_idx)
            cell.font = data_font
            cell.border = border_thin
            if col_idx == 6:
                cell.alignment = Alignment(horizontal="right")
                cell.number_format = "#,##0"
            elif col_idx in [10, 11]:
                cell.alignment = Alignment(horizontal="right")
                cell.number_format = "#,##0.00"
        row_idx += 1

    for col in ws.columns:
        max_len = 0
        col_letter = col[0].column_letter
        for cell in col:
            val_str = str(cell.value or "")
            if len(val_str) > max_len:
                max_len = len(val_str)
        ws.column_dimensions[col_letter].width = max(max_len + 3, 12)

    output = io.BytesIO()
    wb.save(output)
    output.seek(0)
    return output


def generate_csv(headers: list[str], rows: list[list[Any]]) -> io.StringIO:
    """Generate CSV text buffer."""
    output = io.StringIO()
    writer = csv.writer(output)
    writer.writerow(headers)
    for r in rows:
        writer.writerow(r)
    output.seek(0)
    return output
